package io.deepscope.advisor.db;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Idempotent schema for the advisor business database.
 *
 * <p>All business data (accounts, session metadata, event timeline, deliverables) lives in
 * PostgreSQL. The pgvector extension is enabled best-effort so later stages can store knowledge
 * base embeddings in the same database without touching the foundation again.
 */
public final class AdvisorSchema {
    private static final Logger log = LoggerFactory.getLogger(AdvisorSchema.class);

    private AdvisorSchema() {}

    public static void initialize(DataSource dataSource) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement()) {
            enableVectorExtension(statement);
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS accounts (user_id TEXT PRIMARY KEY, username TEXT"
                            + " UNIQUE NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL"
                            + " DEFAULT 'admin', created_at BIGINT NOT NULL)");
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT"
                            + " 'admin'");
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS nickname TEXT NOT NULL DEFAULT"
                            + " ''");
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS remark TEXT NOT NULL DEFAULT"
                            + " ''");
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT"
                            + " 'active'");
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS builtin INTEGER NOT NULL DEFAULT"
                            + " 0");
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS user_number BIGINT GENERATED"
                            + " BY DEFAULT AS IDENTITY");
            statement.execute(
                    "CREATE UNIQUE INDEX IF NOT EXISTS accounts_user_number_uq ON"
                            + " accounts(user_number)");
            // 个人中心：头像落在 advisor.data-dir/avatars，accounts 只记路径与更新时间。
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS avatar_path TEXT NOT NULL"
                            + " DEFAULT ''");
            statement.execute(
                    "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS avatar_updated_at BIGINT NOT"
                            + " NULL DEFAULT 0");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_account_preferences (user_id TEXT PRIMARY"
                        + " KEY, think_enabled INTEGER NOT NULL DEFAULT 0, default_model_id TEXT"
                        + " NOT NULL DEFAULT '', default_agent_id TEXT NOT NULL DEFAULT '',"
                        + " updated_at BIGINT NOT NULL DEFAULT 0)");
            statement.execute(
                    "ALTER TABLE advisor_account_preferences ADD COLUMN IF NOT EXISTS"
                            + " reasoning_effort TEXT NOT NULL DEFAULT 'high'");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_roles (role_id TEXT PRIMARY KEY, name TEXT"
                        + " NOT NULL, code TEXT NOT NULL UNIQUE, description TEXT NOT NULL DEFAULT"
                        + " '', sort_order INTEGER NOT NULL, status TEXT NOT NULL, builtin INTEGER"
                        + " NOT NULL DEFAULT 0, created_at BIGINT NOT NULL)");
            statement.execute(
                    "ALTER TABLE advisor_roles ADD COLUMN IF NOT EXISTS role_number BIGINT"
                            + " GENERATED BY DEFAULT AS IDENTITY");
            statement.execute(
                    "CREATE UNIQUE INDEX IF NOT EXISTS advisor_roles_role_number_uq ON"
                            + " advisor_roles(role_number)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_role_permissions (role_id TEXT NOT NULL,"
                            + " permission TEXT NOT NULL, PRIMARY KEY (role_id, permission))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_account_roles (user_id TEXT NOT NULL,"
                            + " role_id TEXT NOT NULL, PRIMARY KEY (user_id, role_id))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_audit (audit_id TEXT PRIMARY KEY,"
                            + " actor_user_id TEXT NOT NULL, action TEXT NOT NULL, detail TEXT NOT"
                            + " NULL DEFAULT '', created_at BIGINT NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS login_sessions (token_hash TEXT PRIMARY KEY,"
                        + " user_id TEXT NOT NULL REFERENCES accounts(user_id) ON DELETE CASCADE,"
                        + " expires_at BIGINT NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_sessions (session_id TEXT PRIMARY KEY,"
                            + " owner_user_id TEXT NOT NULL, title TEXT NOT NULL, status TEXT NOT"
                            + " NULL, agent_id TEXT NULL, created_at BIGINT NOT NULL, updated_at"
                            + " BIGINT NOT NULL)");
            statement.execute(
                    "ALTER TABLE advisor_sessions ADD COLUMN IF NOT EXISTS agent_id TEXT NULL");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agents (agent_id TEXT PRIMARY KEY, name"
                            + " TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', origin TEXT"
                            + " NOT NULL, owner_user_id TEXT NULL, workspace_dir TEXT NOT NULL,"
                            + " state_dir TEXT NOT NULL, created_at BIGINT NOT NULL, updated_at"
                            + " BIGINT NOT NULL)");
            statement.execute(
                    "ALTER TABLE advisor_agents ADD COLUMN IF NOT EXISTS enabled INTEGER NOT NULL"
                            + " DEFAULT 1");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_events (session_id TEXT NOT NULL REFERENCES"
                        + " advisor_sessions(session_id) ON DELETE CASCADE, seq INTEGER NOT NULL,"
                        + " turn INTEGER NOT NULL, type TEXT NOT NULL, payload TEXT NOT NULL,"
                        + " created_at BIGINT NOT NULL, PRIMARY KEY (session_id, seq))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_deliverables (session_id TEXT NOT NULL"
                        + " REFERENCES advisor_sessions(session_id) ON DELETE CASCADE, version"
                        + " INTEGER NOT NULL, title TEXT NOT NULL, body TEXT NOT NULL, created_at"
                        + " BIGINT NOT NULL, PRIMARY KEY (session_id, version))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_task_boards (session_id TEXT PRIMARY KEY,"
                        + " max_tasks INTEGER NOT NULL, last_updated_at BIGINT NOT NULL, tasks_json"
                        + " TEXT NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_mcp_servers (server_id TEXT PRIMARY KEY,"
                        + " name TEXT NOT NULL, transport TEXT NOT NULL, command TEXT NULL,"
                        + " args_json TEXT NOT NULL DEFAULT '[]', env_json TEXT NOT NULL DEFAULT"
                        + " '{}', url TEXT NULL, headers_json TEXT NOT NULL DEFAULT '{}', status"
                        + " TEXT NOT NULL, status_message TEXT NOT NULL DEFAULT '', owner_user_id"
                        + " TEXT NOT NULL, created_at BIGINT NOT NULL, updated_at BIGINT NOT"
                        + " NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_tools (tool_id TEXT PRIMARY KEY, name TEXT"
                        + " NOT NULL, description TEXT NOT NULL DEFAULT '', input_schema TEXT NOT"
                        + " NULL DEFAULT '{}', origin TEXT NOT NULL, permission TEXT NOT NULL,"
                        + " owner_user_id TEXT NULL, mcp_server_id TEXT NULL, http_method TEXT"
                        + " NULL, http_url TEXT NULL, approved INTEGER NOT NULL DEFAULT 1,"
                        + " created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agent_tools (agent_id TEXT NOT NULL,"
                            + " tool_id TEXT NOT NULL, PRIMARY KEY (agent_id, tool_id))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agent_servers (agent_id TEXT NOT NULL,"
                            + " server_id TEXT NOT NULL, PRIMARY KEY (agent_id, server_id))");
            statement.execute(
                    "ALTER TABLE advisor_tools ADD COLUMN IF NOT EXISTS revision BIGINT NOT NULL"
                            + " DEFAULT 1");
            statement.execute(
                    "ALTER TABLE advisor_tools ADD COLUMN IF NOT EXISTS config_json TEXT NOT NULL"
                            + " DEFAULT '{}'");
            statement.execute(
                    "ALTER TABLE advisor_tools ADD COLUMN IF NOT EXISTS provider_name TEXT NULL");
            statement.execute(
                    "ALTER TABLE advisor_tools ADD COLUMN IF NOT EXISTS lifecycle_status TEXT NOT"
                            + " NULL DEFAULT 'ready'");
            statement.execute(
                    "ALTER TABLE advisor_mcp_servers ADD COLUMN IF NOT EXISTS revision BIGINT NOT"
                            + " NULL DEFAULT 1");
            statement.execute(
                    "ALTER TABLE advisor_mcp_servers ADD COLUMN IF NOT EXISTS pending_json TEXT NOT"
                            + " NULL DEFAULT '[]'");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_tool_credentials (credential_id TEXT"
                            + " PRIMARY KEY, owner_user_id TEXT NOT NULL, ciphertext TEXT NOT NULL,"
                            + " nonce TEXT NOT NULL, created_at BIGINT NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_tool_change_requests (owner_user_id TEXT"
                        + " NOT NULL, request_key TEXT NOT NULL, digest TEXT NOT NULL, result_json"
                        + " TEXT NOT NULL, created_at BIGINT NOT NULL, PRIMARY KEY(owner_user_id,"
                        + " request_key))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_tool_definition_revisions (resource_id TEXT"
                            + " NOT NULL, revision BIGINT NOT NULL, definition_json TEXT NOT NULL,"
                            + " created_at BIGINT NOT NULL, PRIMARY KEY(resource_id, revision))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_skills (skill_id TEXT PRIMARY KEY, name"
                        + " TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', status TEXT NOT"
                        + " NULL, origin TEXT NOT NULL, owner_user_id TEXT NULL, draft_dir TEXT NOT"
                        + " NULL, live_dir TEXT NULL, created_at BIGINT NOT NULL, updated_at BIGINT"
                        + " NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agent_skills (agent_id TEXT NOT NULL,"
                            + " skill_id TEXT NOT NULL, PRIMARY KEY (agent_id, skill_id))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_knowledge_bases (library_id TEXT PRIMARY"
                            + " KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',"
                            + " owner_user_id TEXT NOT NULL, chunk_size INTEGER NOT NULL, overlap"
                            + " INTEGER NOT NULL, recall_limit INTEGER NOT NULL, score_threshold"
                            + " DOUBLE PRECISION NOT NULL, embedding_dimensions INTEGER NULL,"
                            + " embedding_endpoint_id TEXT NULL,"
                            + " created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, UNIQUE"
                            + " (owner_user_id, name))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_documents (document_id TEXT PRIMARY KEY,"
                            + " library_id TEXT NOT NULL, filename TEXT NOT NULL, storage_path TEXT"
                            + " NOT NULL, size_bytes BIGINT NOT NULL, status TEXT NOT NULL, failure"
                            + " TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL, updated_at"
                            + " BIGINT NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agent_libraries (agent_id TEXT NOT NULL,"
                            + " library_id TEXT NOT NULL, PRIMARY KEY (agent_id, library_id))");
            statement.execute(
                    "ALTER TABLE advisor_documents ADD COLUMN IF NOT EXISTS page_count INTEGER NOT"
                            + " NULL DEFAULT 0");
            statement.execute(
                    "ALTER TABLE advisor_documents ADD COLUMN IF NOT EXISTS processed_pages INTEGER"
                            + " NOT NULL DEFAULT 0");
            statement.execute(
                    "ALTER TABLE advisor_documents ADD COLUMN IF NOT EXISTS failed_pages INTEGER"
                            + " NOT NULL DEFAULT 0");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_document_pages (document_id TEXT NOT NULL"
                            + " REFERENCES advisor_documents(document_id) ON DELETE CASCADE,"
                            + " page_number INTEGER NOT NULL, page_json TEXT NOT NULL, PRIMARY"
                            + " KEY(document_id,page_number))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_document_chunks (document_id TEXT NOT NULL"
                        + " REFERENCES advisor_documents(document_id) ON DELETE CASCADE, chunk_id"
                        + " TEXT NOT NULL, library_id TEXT NOT NULL, content TEXT NOT NULL,"
                        + " search_text TEXT NOT NULL, source_json TEXT NOT NULL, PRIMARY"
                        + " KEY(document_id,chunk_id))");
            statement.execute(
                    "CREATE INDEX IF NOT EXISTS advisor_document_chunks_library ON"
                            + " advisor_document_chunks(library_id)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_skill_libraries (skill_id TEXT NOT NULL,"
                            + " library_id TEXT NOT NULL, PRIMARY KEY (skill_id, library_id))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_model_endpoints (endpoint_id TEXT PRIMARY"
                        + " KEY, kind TEXT NOT NULL, provider TEXT NOT NULL, model_name TEXT NOT"
                        + " NULL, base_url TEXT NOT NULL DEFAULT '', secret TEXT NOT NULL,"
                        + " current_flag INTEGER NOT NULL DEFAULT 0, dimensions INTEGER NULL,"
                        + " created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL)");
            statement.execute(
                    "ALTER TABLE advisor_model_endpoints ADD COLUMN IF NOT EXISTS context_window"
                            + " INTEGER");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_model_roles (role_name TEXT PRIMARY KEY,"
                            + " endpoint_id TEXT REFERENCES advisor_model_endpoints(endpoint_id) ON"
                            + " DELETE SET NULL)");
            statement.execute(
                    "INSERT INTO advisor_model_roles(role_name,endpoint_id) SELECT"
                            + " 'knowledge_pdf',NULL WHERE NOT EXISTS (SELECT 1 FROM"
                            + " advisor_model_roles WHERE role_name='knowledge_pdf')");
            statement.execute(
                    "ALTER TABLE advisor_documents ADD COLUMN IF NOT EXISTS stage TEXT NOT NULL"
                            + " DEFAULT ''");
            statement.execute(
                    "ALTER TABLE advisor_documents ADD COLUMN IF NOT EXISTS parse_signature TEXT"
                            + " NOT NULL DEFAULT ''");
            statement.execute(
                    "ALTER TABLE advisor_documents ADD COLUMN IF NOT EXISTS embedded_chunks INTEGER"
                            + " NOT NULL DEFAULT 0");
            statement.execute(
                    "ALTER TABLE advisor_documents ADD COLUMN IF NOT EXISTS total_chunks INTEGER"
                            + " NOT NULL DEFAULT 0");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_document_embedding_checkpoints (document_id"
                        + " TEXT NOT NULL REFERENCES advisor_documents(document_id) ON DELETE"
                        + " CASCADE,chunk_id TEXT NOT NULL,fingerprint TEXT NOT NULL,content_hash"
                        + " TEXT NOT NULL,vector_json TEXT NOT NULL,PRIMARY"
                        + " KEY(document_id,chunk_id))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_document_published_pages (document_id TEXT"
                        + " NOT NULL REFERENCES advisor_documents(document_id) ON DELETE"
                        + " CASCADE,page_number INTEGER NOT NULL,page_json TEXT NOT NULL,PRIMARY"
                        + " KEY(document_id,page_number))");
            statement.execute(
                    "INSERT INTO"
                            + " advisor_document_published_pages(document_id,page_number,page_json)"
                            + " SELECT p.document_id,p.page_number,p.page_json FROM"
                            + " advisor_document_pages p JOIN advisor_documents d ON"
                            + " d.document_id=p.document_id WHERE d.status='ready' AND NOT EXISTS"
                            + " (SELECT 1 FROM advisor_document_published_pages old WHERE"
                            + " old.document_id=p.document_id AND old.page_number=p.page_number)");
            statement.execute(
                    "ALTER TABLE advisor_model_endpoints ADD COLUMN IF NOT EXISTS display_name"
                            + " TEXT NULL");
            statement.execute(
                    "ALTER TABLE advisor_model_endpoints ADD COLUMN IF NOT EXISTS last_test_status"
                            + " TEXT NULL");
            statement.execute(
                    "ALTER TABLE advisor_model_endpoints ADD COLUMN IF NOT EXISTS last_test_at"
                            + " BIGINT NULL");
            statement.execute(
                    "ALTER TABLE advisor_model_endpoints ADD COLUMN IF NOT EXISTS"
                            + " last_test_elapsed_ms BIGINT NULL");
            statement.execute(
                    "ALTER TABLE advisor_model_endpoints ADD COLUMN IF NOT EXISTS last_test_message"
                            + " TEXT NULL");
            statement.execute(
                    "ALTER TABLE advisor_sessions ADD COLUMN IF NOT EXISTS model_endpoint_id TEXT"
                            + " NULL REFERENCES advisor_model_endpoints(endpoint_id) ON DELETE"
                            + " RESTRICT");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_usage_policy (policy_id INTEGER PRIMARY"
                        + " KEY, turn_token_limit INTEGER NOT NULL, daily_task_limit INTEGER NOT"
                        + " NULL, rate_per_minute INTEGER NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_usage_policy (policy_id INTEGER PRIMARY"
                        + " KEY, turn_token_limit INTEGER NOT NULL, daily_task_limit INTEGER NOT"
                        + " NULL, rate_per_minute INTEGER NOT NULL)");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agent_creation_drafts (draft_id TEXT"
                        + " PRIMARY KEY, owner_user_id TEXT NOT NULL, mode TEXT NOT NULL,"
                        + " source_agent_id TEXT NULL, purpose TEXT NOT NULL DEFAULT '', name TEXT"
                        + " NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '', behavior"
                        + " TEXT NOT NULL DEFAULT '', tools_json TEXT NOT NULL DEFAULT '[]',"
                        + " skills_json TEXT NOT NULL DEFAULT '[]', resources_json TEXT NOT NULL"
                        + " DEFAULT '[]', request_key TEXT NULL, request_hash TEXT NULL, revision"
                        + " INTEGER NOT NULL DEFAULT 1, created_at BIGINT NOT NULL, updated_at"
                        + " BIGINT NOT NULL, UNIQUE (owner_user_id, request_key))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agent_creation_operations (operation_id"
                        + " TEXT PRIMARY KEY, draft_id TEXT NOT NULL REFERENCES"
                        + " advisor_agent_creation_drafts(draft_id) ON DELETE CASCADE,"
                        + " operation_type TEXT NOT NULL, request_key TEXT NOT NULL, request_hash"
                        + " TEXT NOT NULL, base_revision INTEGER NOT NULL, state TEXT NOT NULL,"
                        + " stage TEXT NOT NULL DEFAULT '', candidate_json TEXT NULL,"
                        + " preallocated_agent_id TEXT NULL, error_code TEXT NULL, error_message"
                        + " TEXT NULL, started_at BIGINT NOT NULL, finished_at BIGINT NULL, UNIQUE"
                        + " (draft_id, operation_type, request_key))");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_agent_preview_sessions (preview_id TEXT"
                            + " PRIMARY KEY, draft_id TEXT NOT NULL REFERENCES"
                            + " advisor_agent_creation_drafts(draft_id) ON DELETE CASCADE,"
                            + " draft_revision INTEGER NOT NULL, owner_user_id TEXT NOT NULL, state"
                            + " TEXT NOT NULL DEFAULT 'idle', history_json TEXT NOT NULL DEFAULT"
                            + " '[]', created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,"
                            + " expires_at BIGINT NOT NULL)");
            statement.execute(
                    "ALTER TABLE advisor_agents ADD COLUMN IF NOT EXISTS lifecycle TEXT NOT NULL"
                            + " DEFAULT 'active'");
            statement.execute(
                    "ALTER TABLE advisor_agent_creation_drafts ADD COLUMN IF NOT EXISTS"
                            + " activation_state TEXT NOT NULL DEFAULT 'draft'");
            statement.execute(
                    "ALTER TABLE advisor_agent_creation_drafts ADD COLUMN IF NOT EXISTS"
                            + " activated_agent_id TEXT NULL");
            statement.execute(
                    "ALTER TABLE advisor_agent_creation_drafts ADD COLUMN IF NOT EXISTS"
                            + " activation_operation_id TEXT NULL");
            // Initialization precedes request admission: recover only this application's orphaned
            // staging work.
            statement.execute(
                    "DELETE FROM advisor_agent_tools WHERE agent_id IN (SELECT agent_id FROM"
                            + " advisor_agents WHERE lifecycle = 'staging' AND agent_id IN (SELECT"
                            + " activated_agent_id FROM advisor_agent_creation_drafts WHERE"
                            + " activation_state = 'publishing'))");
            statement.execute(
                    "DELETE FROM advisor_agent_skills WHERE agent_id IN (SELECT agent_id FROM"
                            + " advisor_agents WHERE lifecycle = 'staging' AND agent_id IN (SELECT"
                            + " activated_agent_id FROM advisor_agent_creation_drafts WHERE"
                            + " activation_state = 'publishing'))");
            statement.execute(
                    "DELETE FROM advisor_agents WHERE lifecycle = 'staging' AND agent_id IN (SELECT"
                            + " activated_agent_id FROM advisor_agent_creation_drafts WHERE"
                            + " activation_state = 'publishing')");
            statement.execute(
                    "UPDATE advisor_agent_creation_operations SET state='interrupted',"
                        + " stage='startup_recovery', error_code='activation_interrupted' WHERE"
                        + " operation_id IN (SELECT activation_operation_id FROM"
                        + " advisor_agent_creation_drafts WHERE activation_state='publishing') AND"
                        + " state IN ('running','queued')");
            statement.execute(
                    "UPDATE advisor_agent_creation_drafts SET activation_state='draft' WHERE"
                            + " activation_state='publishing'");
            statement.execute(
                    "UPDATE advisor_agent_creation_drafts SET activation_state = 'needs_review'"
                        + " WHERE activation_state = 'draft' AND activation_operation_id IS NULL"
                        + " AND EXISTS (SELECT 1 FROM advisor_agent_creation_operations o WHERE"
                        + " o.draft_id = advisor_agent_creation_drafts.draft_id AND"
                        + " o.operation_type = 'activation' AND o.state = 'succeeded')");
            statement.execute(
                    "UPDATE advisor_agent_creation_drafts SET activation_state = 'activated',"
                        + " activated_agent_id = (SELECT MIN(o.preallocated_agent_id) FROM"
                        + " advisor_agent_creation_operations o WHERE o.draft_id ="
                        + " advisor_agent_creation_drafts.draft_id AND o.operation_type ="
                        + " 'activation' AND o.state = 'succeeded'), activation_operation_id ="
                        + " (SELECT MIN(o.operation_id) FROM advisor_agent_creation_operations o"
                        + " WHERE o.draft_id = advisor_agent_creation_drafts.draft_id AND"
                        + " o.operation_type = 'activation' AND o.state = 'succeeded') WHERE"
                        + " activation_state = 'needs_review' AND activation_operation_id IS NULL"
                        + " AND (SELECT COUNT(*) FROM advisor_agent_creation_operations o WHERE"
                        + " o.draft_id = advisor_agent_creation_drafts.draft_id AND"
                        + " o.operation_type = 'activation' AND o.state = 'succeeded') = 1 AND"
                        + " EXISTS (SELECT 1 FROM advisor_agents a JOIN"
                        + " advisor_agent_creation_operations o ON a.agent_id ="
                        + " o.preallocated_agent_id WHERE o.draft_id ="
                        + " advisor_agent_creation_drafts.draft_id AND o.operation_type ="
                        + " 'activation' AND o.state = 'succeeded')");
            statement.execute(
                    "CREATE TABLE IF NOT EXISTS advisor_commands (command_id TEXT PRIMARY KEY,"
                            + " code TEXT UNIQUE NOT NULL, name TEXT NOT NULL, description TEXT"
                            + " NOT NULL DEFAULT '', origin TEXT NOT NULL DEFAULT 'builtin',"
                            + " owner_user_id TEXT NULL, target_type TEXT NOT NULL, target_id TEXT"
                            + " NULL, params_json TEXT NOT NULL DEFAULT '{}', sort_order INTEGER"
                            + " NOT NULL DEFAULT 100, status TEXT NOT NULL DEFAULT 'active',"
                            + " created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL)");
            statement.execute(
                    "ALTER TABLE advisor_knowledge_bases ADD COLUMN IF NOT EXISTS"
                            + " embedding_endpoint_id TEXT NULL");
            statement.execute(
                    "ALTER TABLE advisor_knowledge_bases ADD COLUMN IF NOT EXISTS index_state TEXT"
                            + " NOT NULL DEFAULT 'ready'");
            statement.execute(
                    "UPDATE advisor_knowledge_bases SET embedding_endpoint_id = ( SELECT"
                            + " endpoint_id FROM advisor_model_endpoints WHERE kind='embedding' AND"
                            + " current_flag=1 LIMIT 1) WHERE embedding_dimensions IS NOT NULL AND"
                            + " embedding_endpoint_id IS NULL");
        }
    }

    /** pgvector is only needed from the knowledge-base stage on, so an unavailable extension is a
     * warning, not a startup failure. */
    private static void enableVectorExtension(Statement statement) {
        try {
            statement.execute("CREATE EXTENSION IF NOT EXISTS vector");
        } catch (SQLException unavailable) {
            log.warn(
                    "pgvector extension unavailable in this database; knowledge base storage will"
                            + " need it later: {}",
                    unavailable.getMessage());
        }
    }
}
