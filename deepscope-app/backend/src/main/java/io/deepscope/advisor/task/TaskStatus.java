package io.deepscope.advisor.task;

/**
 * 结构化中心任务单的生命周期状态。
 */
public enum TaskStatus {
    PENDING,
    BLOCKED,
    READY,
    RUNNING,
    SUCCEEDED,
    FAILED,
    CANCELLED;

    public boolean isTerminal() {
        return this == SUCCEEDED || this == FAILED || this == CANCELLED;
    }

    public boolean isResolved() {
        return this == SUCCEEDED;
    }
}
